/**
 * اختيار سؤال مناسب للحرف والمرحلة الحالية
 * - يُدور بين قائمة الأسئلة بناءً على رقم المرحلة
 * - لا تكرار في المراحل التالية تباعاً
 */
export function getQuestionsForLevel(letter: string, level: number): LetterQuestion[] {
    const pool = LETTER_GAME_QUESTIONS.filter(q => q.letter === letter);
    if (pool.length === 0) return [];

    // المرحلة 1 تأخذ السؤال 0، والمرحلة 2 تأخذ السؤال 1، وهكذا (بدون عشوائية)
    const idx = (level - 1) % pool.length;

    // تدوير القائمة حتى يكون سؤال المرحلة في المقدمة
    return [...pool.slice(idx), ...pool.slice(0, idx)];
}

