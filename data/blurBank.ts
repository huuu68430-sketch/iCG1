type Raw = [en: string, ar: string, tier: BlurTier, hint: string, alt?: string];

const build = (rows: Raw[]): BlurEntry[] => rows.map(([en, ar, tier, hint, alt]) => ({
    en, ar, tier, hint,
    alt: alt ? alt.split('|').map(s => s.trim()).filter(Boolean) : [],
}));

