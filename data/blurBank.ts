export const blurCategoryById = (id: BlurCategoryId | 'random'): BlurCategory | null =>
    BLUR_CATEGORIES.find(c => c.id === id) || null;

/** كلمة عشوائية — من فئة محددة أو من كل الفئات (وضع عشوائي جداً) */
export const pickBlurEntry = (cat: BlurCategoryId | 'random', tier: BlurTier | 0): BlurEntry => {
    const pool = cat === 'random' ? BLUR_ALL : (blurCategoryById(cat)?.entries || BLUR_ALL);
    const filtered = tier === 0 ? pool : pool.filter(e => e.tier === tier);
    const finalPool = filtered.length ? filtered : pool;
    return finalPool[Math.floor(Math.random() * finalPool.length)];
};

/** بحث في البنك بالإجابة العربية (أو إحدى بدولها) — يرجع مصطلح البحث الإنجليزي */
export const findBlurByArabic = (arabic: string): BlurEntry | null => {
    const clean = (s: string) => s
        .replace(/[ً-ْٰ]/g, '')
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/ى/g, 'ي')
        .replace(/ة/g, 'ه')
        .replace(/\s+/g, ' ')
        .trim()
        .toLowerCase();
    const target = clean(arabic);
    if (!target) return null;
    return BLUR_ALL.find(e =>
        clean(e.ar) === target || e.alt.some(a => clean(a) === target)
    ) || null;
};
