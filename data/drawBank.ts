export interface PickOptions {
    categories?: DrawCategoryId[];
    tiers?: DrawTier[];
    count?: number;
    used?: Set<string>;
    exclude?: string[];
}

function shuffled<T>(arr: T[]): T[] {
    const out = [...arr];
    for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
}

export function pickDrawWords(opts: PickOptions = {}): DrawEntry[] {
    const count = opts.count ?? 3;
    const used = opts.used || new Set<string>();
    const exclude = new Set([...(opts.exclude || []), ...used]);
    const cats = opts.categories && opts.categories.length
        ? DRAW_CATEGORIES.filter(c => opts.categories!.includes(c.id))
        : DRAW_CATEGORIES;
    const tiers = opts.tiers && opts.tiers.length ? new Set(opts.tiers) : null;
    let pool = cats.flatMap(c => c.entries);
    if (tiers) pool = pool.filter(e => tiers.has(e.tier));
    pool = pool.filter(e => !exclude.has(e.ar));
    const picked = shuffled(pool).slice(0, count);
    // إذا فرغ المخزن أعد ملأه بالكلمات المستعملة نفسها
    if (picked.length < count && used.size) {
        const again = shuffled(pool.concat(DRAW_ALL.filter(e => used.has(e.ar)))).slice(0, count);
        return again;
    }
    return picked;
}

export function randomDrawWord(): DrawEntry {
    return pickDrawWords({ count: 1 })[0] || DRAW_ALL[0];
}

