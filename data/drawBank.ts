// بنك كلمات لعبة الرسم.
// قسمان: كلمات مُصنّفة مختارة (فئات + تلميح + أشكال مقبولة) + المكتبة الأصلية (415 كلمة) مُدمجة تلقائياً.
// التلميح اختياري في المكتبة الأصلية: عندها يستخدم اللعبة «أول حرف + عدد الحروف».

import { LEGACY_EASY, LEGACY_MID, LEGACY_HARD } from './drawLegacy';

export type DrawTier = 1 | 2 | 3;

export type DrawCategoryId =
    | 'places' | 'landmarks' | 'animals' | 'sea' | 'birds'
    | 'nature' | 'food' | 'sweets' | 'sports' | 'fantasy'
    | 'jobs' | 'transport' | 'general';

export interface DrawEntry {
    id: string;
    ar: string;
    tier: DrawTier;
    hint: string;
    alt: string[];
    categoryId: DrawCategoryId;
}

export interface DrawCategory {
    id: DrawCategoryId;
    label: string;
    blurb: string;
    hex: string;
    entries: DrawEntry[];
}

export const DRAW_TIERS: Record<DrawTier, { label: string; hex: string; points: number }> = {
    1: { label: 'سهل', hex: '#4be07a', points: 100 },
    2: { label: 'متوسط', hex: '#e8be6e', points: 150 },
    3: { label: 'صعب', hex: '#e8552f', points: 220 },
};

type Raw = [string, DrawTier, string?, string?];

const used = new Set<string>();
const CATS: DrawCategory[] = [];

function category(id: DrawCategoryId, label: string, blurb: string, hex: string, raws: Raw[]) {
    const entries: DrawEntry[] = [];
    for (const r of raws) {
        const key = r[0].trim();
        if (used.has(key)) continue;
        used.add(key);
        entries.push({
            id: `${id}${entries.length}`,
            ar: key,
            tier: r[1],
            hint: (r[2] || '').trim(),
            alt: (r[3] || '').split('|').map(s => s.trim()).filter(Boolean),
            categoryId: id,
        });
    }
    CATS.push({ id, label, blurb, hex, entries });
}

