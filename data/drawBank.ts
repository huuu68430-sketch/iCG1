export function canon(s: string): string {
    return String(s || '')
        .replace(/[ً-ْٰـ]/g, '')
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/ى/g, 'ي')
        .replace(/ئ/g, 'ي')
        .replace(/ؤ/g, 'و')
        .replace(/ة/g, 'ه')
        .replace(/[\u200e\u200f\u00a0]/g, ' ')
        .replace(/[^ؠ-يA-Za-z0-9]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim()
        .toLowerCase();
}

function stripArticle(text: string): string {
    return text.replace(/^ال/, '').replace(/^(ه|و|ف)\s+/, '').trim();
}

/** كل الأشكال المقبولة للكلمة: الأصل + البدائل + مجردة من «ال» */
export function drawGuessForms(entry: DrawEntry): Set<string> {
    const forms = new Set<string>();
    for (const raw of [entry.ar, ...entry.alt]) {
        const c = canon(raw);
        if (!c) continue;
        forms.add(c);
        const bare = stripArticle(c);
        if (bare) forms.add(bare);
    }
    return forms;
}

export function matchDrawGuess(raw: string, entry: DrawEntry): boolean {
    const text = canon(stripArticle(canon(raw)));
    if (!text) return false;
    const forms = drawGuessForms(entry);
    if (forms.has(text) || forms.has(stripArticle(text))) return true;
    // كلمات مركبة: «كرة قدم» تُقبل بـ«قدم» بعد «كرة»، والعكس مرفوض حتى لا نغلّط أحد
    for (const f of forms) {
        if (f.includes(' ') && (text.includes(f) || f.includes(text) && text.length >= 3)) return true;
    }
    const target = entry.ar.split(/\s+/).filter(w => w.length > 2);
    if (target.length > 1) {
        const hits = target.filter(w => forms.has(stripArticle(canon(w)))).length;
        const said = text.split(' ');
        const matched = target.filter(w => said.includes(stripArticle(canon(w)))).length;
        if (matched >= Math.max(2, Math.ceil(target.length * 0.99))) return true;
        if (hits && matched >= hits) return true;
    }
    return false;
}

export function findDrawByArabic(raw: string): DrawEntry | undefined {
    const text = canon(stripArticle(canon(raw)));
    if (!text) return undefined;
    return DRAW_ALL.find(e => {
        const forms = drawGuessForms(e);
        return forms.has(text) || forms.has(stripArticle(text));
    });
}

/** أول حرف + عدد الحروف، للشكل المكتوب بلا مسافات */
export function drawPattern(entry: DrawEntry, revealed = 1): string {
    const letters = entry.ar.replace(/\s+/g, ' ').split(' ').map(w => [...w]);
    return letters.map((word, wi) => word.map((ch, ci) =>
        (wi === 0 && ci < revealed) || ch === 'ْ' ? ch : ' '
    ).join('') || ' ').join(' ');
}

export function drawLetterCount(entry: DrawEntry): number {
    return entry.ar.replace(/\s/g, '').length;
}

